/**
 * Every failure: an invalid request, a failed render (not charged), a network problem. `message` says what to do
 * next; `code` is stable, for your code.
 */
export class GepettoError extends Error {
  readonly code: ErrorCode;
  /** HTTP status, or null when the API was not reached. */
  readonly status: number | null;
  /** The request field at fault, when there is one. */
  readonly param?: string;
  /** The job, when the error concerns a render (it can be followed with `getJob`). */
  readonly jobId?: string;
  readonly job?: Job;

  constructor(init: { code: ErrorCode; message: string; status?: number | null; param?: string; jobId?: string; job?: Job; cause?: unknown }) {
    super(init.message, init.cause === undefined ? undefined : { cause: init.cause });
    this.name = 'GepettoError';
    this.code = init.code;
    this.status = init.status ?? null;
    if (init.param) this.param = init.param;
    if (init.jobId) this.jobId = init.jobId;
    if (init.job) this.job = init.job;
  }
}

