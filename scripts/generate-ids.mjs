// Refreshes the known ids (rooms, styles, furniture, skies, walls, floors, finishes) in src/index.ts, between the
// `// <ids>` and `// </ids>` markers, from the live lists of the API. They only feed the editor's autocomplete: every
// id type also accepts any other string, so an id added on the server works before the SDK is republished.
//
//   GEPETTO_API_KEY=test_... node scripts/generate-ids.mjs
import fs from 'node:fs';

const BASE = process.env.GEPETTO_BASE_URL || 'https://europe-west1-gepettoai.cloudfunctions.net/v2';
const KEY = process.env.GEPETTO_API_KEY;
if (!KEY) {
  console.error('Set GEPETTO_API_KEY (a test key is enough).');
  process.exit(1);
}

async function get(path) {
  const res = await fetch(`${BASE}${path}`, { headers: { Authorization: `Bearer ${KEY}` } });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status} ${await res.text()}`);
  return res.json();
}

const [rooms, styles, furnitures, skies, surfaces] = await Promise.all([
  get('/rooms'), get('/styles'), get('/furnitures'), get('/skies'), get('/surfaces'),
]);

const union = (ids) => [...new Set(ids)].sort().map((id) => `'${id}'`).join(' | ') || 'never';
const line = (name, doc, ids) => `/** ${doc} */\nexport type ${name} = ${union(ids)};`;

const block = [
  '// <ids>',
  `// Generated by scripts/generate-ids.mjs on ${new Date().toISOString().slice(0, 10)}: do not edit by hand.`,
  line('KnownRoomId', 'Rooms of `GET /rooms`.', rooms.map((r) => r.id)),
  line('KnownAutoRoomId', 'Rooms that can be furnished whole, without a mask (mode `auto`).', rooms.filter((r) => r.modes?.includes('auto')).map((r) => r.id)),
  line('KnownZoneRoomId', 'Rooms that can furnish the zone of a mask (mode `zone`).', rooms.filter((r) => r.modes?.includes('zone')).map((r) => r.id)),
  line('KnownStyleId', 'Styles of `GET /styles`.', styles.map((s) => s.id)),
  line('KnownFurnitureId', 'Pieces of furniture of `GET /furnitures`.', Object.values(furnitures).flat().map((f) => f.id)),
  line('KnownSkyId', 'Skies of `GET /skies`.', skies.map((s) => s.id)),
  line('KnownWallTypeId', 'Wall colours of `GET /surfaces` (`custom` takes `customWallColor`).', surfaces.walls.map((w) => w.id)),
  line('KnownFloorTypeId', 'Floors of `GET /surfaces`.', surfaces.floors.map((f) => f.id)),
  line('KnownFinishId', 'Finishes of `GET /surfaces`.', surfaces.finishes.map((f) => f.id)),
  '// </ids>',
].join('\n');

const file = new URL('../src/index.ts', import.meta.url);
const src = fs.readFileSync(file, 'utf8');
const next = src.replace(/\/\/ <ids>[\s\S]*?\/\/ <\/ids>/, block);
if (next === src && !src.includes(block)) throw new Error('markers // <ids> ... // </ids> not found in src/index.ts');
fs.writeFileSync(file, next);
console.log('src/index.ts: ids refreshed.');
